import { _electron as electron } from 'playwright';
import electronPath from 'electron';
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root=path.resolve(fileURLToPath(new URL('..',import.meta.url)));
const output=path.join(root,'build/qa/navigation-20260926');await mkdir(output,{recursive:true});
const dataDir=await mkdtemp(path.join(os.tmpdir(),'awb-runtime-ui-'));
const folder=path.join(dataDir,'Project');await mkdir(folder);
const checks=[],errors=[],pids=[];let app,page;
const record=name=>{checks.push(name);console.log('PASS '+name);};
const launch=async()=>{
 app=await electron.launch({executablePath:electronPath,args:[root],cwd:root,env:{...process.env,AGENT_WORKBENCH_TEST_DATA:dataDir,ELECTRON_RUN_AS_NODE:undefined}});
 pids.push(app.process().pid);page=await app.firstWindow();page.setDefaultTimeout(10000);page.on('pageerror',e=>errors.push(e.message));
 await page.waitForFunction(()=>document.querySelector('[data-testid="composer-runtime"]')?.disabled===false);
};
const call=(method,payload={})=>page.evaluate(({method,payload})=>window.workbench.call(method,payload),{method,payload});
const choice=async runtime=>{await page.getByTestId('composer-runtime').click();await page.getByRole('menu',{name:'运行时',exact:true}).locator(`[data-value="${runtime}"]`).click();};
const runtimeIs=async runtime=>{const labels={codex:'Codex',claude:'Claude',demo:'离线示例'};await page.waitForFunction(label=>document.querySelector('[data-testid="composer-runtime"]')?.textContent===label,labels[runtime]);};
const saved=async runtime=>{await page.waitForFunction(async value=>(await window.workbench.call('state/get')).lastSelectedRuntime===value,runtime);};
const newFor=async id=>{await page.locator(`[data-project-id="${id}"] .project-heading`).hover();await page.getByTestId(`project-new-session-${id}`).click();};
const command=id=>app.evaluate(({Menu,BrowserWindow},id)=>Menu.getApplicationMenu().getMenuItemById(id).click(undefined,BrowserWindow.getAllWindows()[0],{}),id);
try {
 await launch();await runtimeIs('demo');
 const project=await call('project/create',{name:'运行时测试项目',paths:[folder]});
 const old=await call('session/create',{runtime:'demo',permissionMode:'read-only'});
 await call('session/update',{id:old.id,title:'旧的离线会话'});
 await call('project/update',{id:'__recent__',paths:[folder]});
 await page.getByTestId('composer-input').fill('切换后保留输入草稿');
 await choice('claude');await runtimeIs('claude');assert.equal(await page.getByTestId('composer-input').inputValue(),'切换后保留输入草稿');
 await page.getByTestId('new-session').click();await runtimeIs('claude');await saved('claude');
 assert.equal((await call('state/get')).sessions.length,1);record('explicit runtime selection keeps the draft and new chats inherit it before sending');
 await newFor(project.id);await runtimeIs('claude');assert.equal((await page.getByTestId('composer-project').innerText()).trim(),project.name);
 await newFor('__recent__');await runtimeIs('claude');assert.equal((await page.getByTestId('composer-project').innerText()).trim(),'选择项目');
 await command('new-session');await runtimeIs('claude');await page.keyboard.press('Control+n');await runtimeIs('claude');
 record('global, project, recent, menu and keyboard new-chat entrypoints share the remembered runtime');
 await choice('codex');await page.getByTestId('new-session').click();await runtimeIs('codex');await saved('codex');
 await page.getByTestId(`sidebar-session-${old.id}`).locator('.session-select').click();await runtimeIs('demo');
 await page.getByTestId('new-session').click();await runtimeIs('codex');
 assert.deepEqual((await call('state/get')).sessions.find(s=>s.id===old.id).binding,old.binding);
 assert.equal((await call('state/get')).sessions.find(s=>s.id===old.id).permissionMode,'read-only');
 record('opening older history cannot overwrite the runtime preference or its saved session identity');
 await page.getByTestId('composer-project').click();assert.equal((await page.getByTestId('project-option-none').innerText()).trim(),'不关联项目');assert.doesNotMatch(await page.getByTestId('project-picker').innerText(),/最近会话/);
 await page.screenshot({path:path.join(output,'no-project-light.png')});await page.getByTestId('project-option-none').click();
 await app.close();app=null;await launch();await runtimeIs('codex');await saved('codex');assert.notEqual(pids[0],pids[1]);
 await page.getByTestId('new-session').click();await runtimeIs('codex');
 await page.screenshot({path:path.join(output,'runtime-after-restart.png')});
 record('a real Electron process restart restores Codex on the first blank chat and subsequent new chats');
 await choice('claude');await choice('demo');await choice('codex');await page.keyboard.press('Control+n');await runtimeIs('codex');await saved('codex');
 record('rapid successive selections and immediate new-chat creation retain the final choice');
 await choice('demo');await saved('demo');await app.close();app=null;await launch();await runtimeIs('demo');
 assert.equal((await call('state/get')).sessions.length,1);record('explicitly returning to demo persists across another restart without creating empty sessions');
 assert.deepEqual(errors,[]);
 await writeFile(path.join(output,'runtime-report.json'),JSON.stringify({passed:true,timestamp:new Date().toISOString(),checks,errors,pids,dataDir,scope:'Isolated profile; actual Electron restarts, synthetic history; no models, SSH or credentials.'},null,2));
 console.log(`Runtime desktop QA: ${checks.length} checks passed`);
} catch(error) {await writeFile(path.join(output,'runtime-failure.json'),JSON.stringify({error:String(error.stack??error),checks,errors},null,2));if(page)try{await page.screenshot({path:path.join(output,'runtime-failure.png')});}catch{}throw error;}
finally {if(app)await app.close();}

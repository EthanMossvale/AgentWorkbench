import assert from 'node:assert/strict';
import path from 'node:path';
import { readFile, writeFile } from 'node:fs/promises';
import { collectDirectory, encodeZip } from '../packages/native-resources/archive.ts';
import { openWorkbenchSettings } from './ui-control-helpers.mjs';

export async function checkPluginUi({app,page,call,output,put,record}) {
  await call('theme/set',{theme:'dark'});
  await openWorkbenchSettings(page,'plugins');
  await page.getByRole('tab',{name:'工作台插件',exact:true}).click();
  await page.getByTestId('translation-plugin-expand').click();
  await page.getByTestId('translation-endpoint').waitFor();
  assert.equal(await page.locator('.translation-heading').count(),0);
  assert.equal(await page.getByTestId('translation-module-enabled').count(),0);
  assert.equal(await page.getByLabel('启用双语工作流',{exact:true}).count(),1);
  await page.getByTestId('translation-plugin-expand').click();
  await page.getByRole('tab',{name:'运行时插件',exact:true}).click();
  assert.equal(await page.getByTestId('translation-plugin').count(),0);
  assert.equal(await page.getByTestId('plugin-import').count(),0);
  assert.equal(await page.getByTestId('plugin-list-note').count(),0);
  await page.getByRole('tab',{name:/已安装/}).waitFor();
  await page.screenshot({path:path.join(output,'runtime-plugin-tabs-dark.png')});
  await page.getByRole('tab',{name:'运行时插件',exact:true}).press('ArrowLeft');
  assert.equal(await page.getByRole('tab',{name:'工作台插件',exact:true}).getAttribute('aria-selected'),'true');
  await page.getByTestId('plugin-list-note').waitFor();
  await page.screenshot({path:path.join(output,'workbench-plugin-tabs-dark.png')});
  record('workbench/runtime tabs partition both lists and help, keyboard navigation works, and translation has one switch');

  await page.getByTestId('settings-memory').click();
  const codex = page.getByLabel('Codex 原生记忆',{exact:true}), tools = page.getByLabel('允许从使用工具的聊天中形成记忆',{exact:true});
  await codex.uncheck();
  await page.waitForFunction(()=>!document.querySelector('.memory-tool-setting').disabled);
  await tools.uncheck();
  await page.waitForFunction(()=>!document.querySelector('.memory-tool-setting').disabled);
  await tools.check();
  await page.waitForFunction(()=>!document.querySelector('.memory-tool-setting').disabled);
  const settings = (await call('native-memory/settings/get')).find(s=>s.runtime==='codex');
  assert.equal(settings.enabled,false); assert.equal(settings.allowToolChats,true);
  const geometry = await page.getByTestId('memory-control-codex').locator('fieldset').evaluateAll(elements=>elements.map(e=>e.getBoundingClientRect().left));
  assert.equal(geometry[0],geometry[1]);
  assert.equal(await page.getByTestId('memory-control-claude').getByRole('checkbox').count(),1);
  await page.screenshot({path:path.join(output,'memory-parallel-dark.png')});
  await codex.check(); await page.waitForFunction(()=>!document.querySelector('.memory-tool-setting').disabled);
  record('Codex source preference saves while memory is disabled, rows align, and Claude shows one verified auto-memory switch');

  const zip = path.join(output,'shell-plugin.zip');
  await put(zip,encodeZip(await collectDirectory(path.resolve('examples/plugins/shell-workspace'))));
  await openWorkbenchSettings(page,'plugins');
  const beforeImport=(await call('extensions/list')).length;
  await app.evaluate(({dialog})=>{globalThis.__pluginPickCount=0;dialog.showOpenDialog=async()=>{globalThis.__pluginPickCount++;return {canceled:true,filePaths:[]};};});
  await page.getByTestId('plugin-import').click();
  const importDialog=page.getByRole('dialog',{name:'导入工作台插件',exact:true}),dropzone=page.getByTestId('plugin-zip-dropzone');
  await dropzone.waitFor();assert.equal(await importDialog.getByRole('tab').count(),0);assert.equal(await app.evaluate(()=>globalThis.__pluginPickCount),0);assert.equal((await call('extensions/list')).length,beforeImport);
  await page.screenshot({path:path.join(output,'plugin-dropzone-dark.png')});
  await dropzone.click();await page.waitForFunction(()=>!document.querySelector('[data-testid=plugin-zip-dropzone]').disabled);await importDialog.waitFor();assert.equal(await app.evaluate(()=>globalThis.__pluginPickCount),1);
  const cdp=await page.context().newCDPSession(page);
  const dragFiles=async files=>{const box=await dropzone.boundingBox(),x=box.x+box.width/2,y=box.y+box.height/2,data={items:[],files,dragOperationsMask:1};for(const type of ['dragEnter','dragOver','drop'])await cdp.send('Input.dispatchDragEvent',{type,x,y,data});};
  const text=path.join(output,'not-a-plugin.txt');await put(text,'Fixture');await dragFiles([text]);await importDialog.getByRole('alert').filter({hasText:'ZIP 格式'}).waitFor();
  await dragFiles([zip,text]);await importDialog.getByRole('alert').filter({hasText:'一次拖入一个'}).waitFor();assert.equal((await call('extensions/list')).length,beforeImport);
  await call('theme/set',{theme:'light'});await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setContentSize(860,640));await page.waitForFunction(()=>innerWidth===860);
  await page.screenshot({path:path.join(output,'plugin-dropzone-light-narrow.png')});assert.equal(await importDialog.evaluate(e=>e.scrollWidth>e.clientWidth||e.getBoundingClientRect().bottom>innerHeight),false);
  await dragFiles([zip]);await importDialog.waitFor({state:'detached'});assert.equal(await app.evaluate(()=>globalThis.__pluginPickCount),1);
  await page.getByTestId('plugin-import').click();await dragFiles([zip]);await importDialog.getByRole('alert').filter({hasText:'已安装同名'}).waitFor();assert.equal((await call('extensions/list')).length,beforeImport+1);await page.keyboard.press('Escape');await importDialog.waitFor({state:'detached'});await cdp.detach();
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setContentSize(1440,940));await page.waitForFunction(()=>innerWidth===1440);
  record('compact plugin ZIP modal has no runtime tabs; cancellation, invalid/multiple/duplicate ZIP and real file drop preserve existing installs');
  const toggle = page.getByLabel('启用 专注工作台示例',{exact:true});
  await toggle.waitFor(); assert.equal(await toggle.isChecked(),false);
  await toggle.click(); await page.getByRole('dialog').waitFor();
  await page.getByRole('button',{name:'取消',exact:true}).click(); assert.equal(await toggle.isChecked(),false);
  await toggle.click(); await page.getByTestId('plugin-approve-host').click();
  const surface = page.locator('[data-plugin-surface="example.shell-workspace"]');
  await surface.waitFor({state:'visible'});
  assert.equal(await page.locator('#root').evaluate(e=>e.hidden),true);
  await call('theme/set',{theme:'light'}); await page.getByTestId('plugin-shell-theme').filter({hasText:'light'}).waitFor();
  await page.screenshot({path:path.join(output,'replacement-shell.png')});
  await page.getByRole('button',{name:'停用插件并恢复工作台',exact:true}).click();
  await surface.waitFor({state:'detached'}); assert.equal(await page.locator('#root').evaluate(e=>e.hidden),false);
  assert.equal(await page.locator('style[data-plugin="example.shell-workspace"]').count(),0);
  record('approved bundled plugin replaces the complete shell, invokes host commands, observes state and restores UI/styles on disable');

  let plugin = (await call('extensions/list')).find(p=>p.manifest.id==='example.shell-workspace');
  await call('extensions/toggle',{id:plugin.manifest.id,hash:plugin.hash,enabled:true}); await surface.waitFor({state:'visible'});
  await app.evaluate(({Menu})=>Menu.getApplicationMenu().getMenuItemById('recover-plugins').click());
  assert.equal((await call('plugin-recovery/show')).shown,true);
  assert.equal((await call('extensions/list')).find(p=>p.manifest.id===plugin.manifest.id).enabled,true);
  await call('extensions/disable-all');
  await page.waitForFunction(()=>document.querySelector('#root').hidden===false);
  assert.equal((await call('extensions/list')).find(p=>p.manifest.id===plugin.manifest.id).enabled,false);
  record('native recovery menu opens independent diagnosis; explicit disable still restores the base shell');

  await call('extensions/toggle',{id:plugin.manifest.id,hash:plugin.hash,enabled:true}); await surface.waitFor({state:'visible'});
  const file = path.join(plugin.directory,'renderer.mjs');
  await writeFile(file,(await readFile(file,'utf8'))+'\n// Changed version for approval regression.\n');
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await surface.waitFor({state:'detached'});
  plugin = (await call('extensions/list')).find(p=>p.manifest.id===plugin.manifest.id);
  assert.equal(plugin.approved,false); assert.equal(plugin.enabled,false);
  assert.equal(await page.locator('#root').evaluate(e=>e.hidden),false);
  record('package mutation revokes renderer approval and removes its active shell');

  await writeFile(file,`export function activate(api) { api.addStyle('body { --plugin-failure-test: 1 }'); api.replaceShell(); document.documentElement.dataset.pluginFailureObserved = '1'; throw Error('Expected QA activation failure'); }`);
  plugin = (await call('extensions/list')).find(p=>p.manifest.id===plugin.manifest.id);
  await call('extensions/toggle',{id:plugin.manifest.id,hash:plugin.hash,enabled:true,approveHost:true});
  await page.waitForFunction(()=>document.documentElement.dataset.pluginFailureObserved==='1' && document.querySelector('#root').hidden===false && !document.querySelector('[data-plugin-surface="example.shell-workspace"]'));
  await page.waitForFunction(async ()=>(await window.workbench.call('extensions/list')).some(p=>p.manifest.id==='example.shell-workspace' && p.error==='PLUGIN_RENDERER_ACTIVATION_FAILED'));
  assert.equal(await page.locator('style[data-plugin="example.shell-workspace"]').count(),0);
  await call('extensions/disable-all');
  record('activation failure removes partial styles and shell ownership without breaking the workbench');

  await writeFile(file,`export async function activate(api) { api.addStyle('body { --plugin-pending-test: 1 }'); document.documentElement.dataset.pluginPendingObserved='1'; await new Promise(resolve => { window.__finishPluginQa = resolve; }); api.replaceShell(); }`);
  plugin = (await call('extensions/list')).find(p=>p.manifest.id===plugin.manifest.id);
  await call('extensions/toggle',{id:plugin.manifest.id,hash:plugin.hash,enabled:true,approveHost:true});
  await page.waitForFunction(()=>document.documentElement.dataset.pluginPendingObserved==='1');
  await call('extensions/disable-all'); await surface.waitFor({state:'detached'});
  await page.evaluate(()=>window.__finishPluginQa());
  assert.equal(await page.locator('#root').evaluate(e=>e.hidden),false);
  assert.equal(await page.locator('style[data-plugin="example.shell-workspace"]').count(),0);
  record('disabling during asynchronous activation prevents a late shell takeover and removes pending styles');

  await openWorkbenchSettings(page,'plugins');
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setContentSize(860,640));
  await page.waitForFunction(()=>innerWidth===860);
  await page.screenshot({path:path.join(output,'plugin-tabs-light-narrow.png')});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  record('plugin tabs and footer fit the narrow light-theme window');
}
